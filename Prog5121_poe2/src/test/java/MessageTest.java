import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import static org.junit.jupiter.api.Assertions.*;

/**
 *
 * @author leago
 */
public class MessageTest {
    
    @AfterEach
    void tearDown() {
        Message.resetSession();
    }

    // ---------- checkMessageID() ----------

    @Test
    void checkMessageID_AutoGeneratedID_IsNoMoreThanTenCharacters() {
        Message message = new Message("+27718693002",
                "Hi Mike, can you join us for dinner tonight?", 0);
        assertTrue(message.checkMessageID());
        assertTrue(message.getMessageID().length() <= 10);
    }

    // ---------- checkMessageLength() ----------

    @Test
    void checkMessageLength_WithinLimit_ReturnsReadyToSend() {
        String shortMessage = "Hi Mike, can you join us for dinner tonight?";
        assertEquals("Message ready to send.", Message.checkMessageLength(shortMessage));
    }

    @Test
    void checkMessageLength_OverLimit_ReturnsExceedsMessage() {
        String longMessage = "a".repeat(260); // 10 characters over the 250 limit
        assertEquals("Message exceeds 250 characters by 10; please reduce the size.",
                Message.checkMessageLength(longMessage));
    } 
   
}
